  values.push(`1:17:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`1:18:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`1:19:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`1:20:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`1:21:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`1:22:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`1:23:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`1:24:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
