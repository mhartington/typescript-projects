  values.push(`1:0:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`1:1:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`1:2:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`1:3:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
