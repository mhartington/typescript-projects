  values.push(`501:16:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`501:17:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`501:18:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`501:19:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`501:20:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
  values.push(`501:21:${cpuCount}:${url.pathname ?? "none"}:${digest}:${id}`);
